for name, fn in [('по дню недели', lambda h,t: predict_dow(h,t)),
                 ('среднее за 28 дн.', lambda h,t: h.tail(28).mean()),
                 ('наивный (вчера)', lambda h,t: h.iloc[-1])]:
    preds = [fn(hist[hist.index<d], d) for d in bt_dates]
